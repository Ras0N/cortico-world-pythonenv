import { spawn, execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { delimiter, join } from 'node:path';
import { writeDebug, writeDebugOutputFiles } from '../debug-log.ts';
import { VENV_STATE_DIR } from '../layout.ts';
import type { CommandRunner, RunRequest, RunResult } from './types.ts';

/** glibc：提高 IPv4 映射地址优先级，让 getaddrinfo（含 C 层）先试 IPv4。 */
export const GAI_CONF_PREFER_IPV4 = `# generated by cortico-world-pythonenv — prefer IPv4 (Hyper-V/VM IPv6 blackhole workaround)
precedence :ffff:0:0/96  100
`;

/** Ubuntu 22.04 / Debian 13 安装提示（缺 bwrap 时硬失败文案）。 */
export const BWRAP_INSTALL_HINT =
  'bubblewrap (bwrap) is required but was not found on PATH. ' +
  'On Ubuntu 22.04 LTS / Debian 13: sudo apt update && sudo apt install bubblewrap';

/** 只读挂进沙箱的系统根（存在才绑；用 --ro-bind-try 避免缺失项失败）。 */
export const BWRAP_SYSTEM_ROOTS = [
  '/usr',
  '/lib',
  '/lib64',
  '/lib32',
  '/bin',
  '/sbin',
  '/etc',
  '/opt',
] as const;

/**
 * DNS / systemd-resolved：现代 Debian/Ubuntu 上 `/etc/resolv.conf` 常是指向
 * `/run/systemd/resolve/...` 的符号链接；只绑 `/etc` 不绑 `/run` 会导致
 * `Temporary failure in name resolution`（不是黑名单拦截）。
 */
export const BWRAP_DNS_ROOTS = [
  '/run/systemd/resolve',
  '/var/run/systemd/resolve',
  '/run/resolvconf',
  '/var/run/resolvconf',
] as const;

/** CA / 证书相关（部分发行版把实体放在 /var/lib 下，仅绑 /etc 不够）。 */
export const BWRAP_CERT_ROOTS = ['/var/lib/ca-certificates', '/usr/local/share/ca-certificates'] as const;

export interface BwrapArgvOptions {
  workDirAbs: string;
  cwd: string;
  command: string;
  env?: Record<string, string>;
  readonlyPaths?: string[];
  /** 覆盖系统根列表（测试用）。 */
  systemRoots?: readonly string[];
  /** 沙箱内 /tmp 对应的宿主目录；默认 workDir/venv-state/tmp。 */
  tmpHostDir?: string;
}

/**
 * 解析 `bwrap` 可执行文件；找不到则抛错（硬失败，不降级）。
 */
export function resolveBwrapBinary(platform: NodeJS.Platform = process.platform): string {
  if (platform !== 'linux') {
    throw new Error('cortico-world-pythonenv bubblewrap runner supports Linux only.');
  }
  try {
    const out = execFileSync('/bin/sh', ['-c', 'command -v -- bwrap'], { encoding: 'utf8' });
    const bin = out.trim().split(/\r?\n/)[0]?.trim();
    if (bin && existsSync(bin)) return bin;
  } catch {
    /* fall through */
  }
  throw new Error(BWRAP_INSTALL_HINT);
}

/** 组装 bwrap argv（不含二进制名本身）。末尾为 `-- /bin/sh -c <command>`。 */
export function buildBwrapArgv(opts: BwrapArgvOptions): string[] {
  const work = opts.workDirAbs.replace(/\/+$/, '') || opts.workDirAbs;
  const cwd = opts.cwd.replace(/\/+$/, '') || opts.cwd;
  const tmpHost = opts.tmpHostDir ?? join(work, VENV_STATE_DIR, 'tmp');
  mkdirSync(tmpHost, { recursive: true });

  const args: string[] = [
    '--die-with-parent',
    '--new-session',
    '--unshare-pid',
    '--unshare-uts',
    '--unshare-ipc',
    // 故意不 --unshare-net：保留出站；黑名单由 sitecustomize / 工具扫描执行
    '--dev',
    '/dev',
    '--proc',
    '/proc',
  ];

  const roots = opts.systemRoots ?? BWRAP_SYSTEM_ROOTS;
  for (const root of roots) {
    args.push('--ro-bind-try', root, root);
  }
  for (const root of BWRAP_DNS_ROOTS) {
    args.push('--ro-bind-try', root, root);
  }
  for (const root of BWRAP_CERT_ROOTS) {
    args.push('--ro-bind-try', root, root);
  }

  // workDir 可读写（我们只绑了系统根，不绑整棵 /）
  args.push('--bind', work, work);

  // 若 workDir 在宿主 /tmp 下，再把 /tmp 绑成别的目录会把 workDir 盖掉（chdir 报 No such file）。
  // 此时不重挂 /tmp，只用 TMPDIR 指到 workDir/venv-state/tmp。
  const workUnderHostTmp = isInsideWorkDir(work, '/tmp');
  let tmpInSandbox = '/tmp';
  if (workUnderHostTmp) {
    tmpInSandbox = tmpHost;
  } else {
    args.push('--bind', tmpHost, '/tmp');
  }

  for (const p of uniquePaths(opts.readonlyPaths ?? [])) {
    if (!p || isInsideWorkDir(p, work)) continue;
    args.push('--ro-bind-try', p, p);
  }

  // 无 TTY 时 Python 块缓冲，超时被杀会变成 exit≠0 且 stdout/stderr 全空，难排查
  const caBundle = '/etc/ssl/certs/ca-certificates.crt';
  const env: Record<string, string> = {
    PATH: ['/usr/bin', '/bin', '/usr/sbin', '/sbin'].join(delimiter),
    HOME: work,
    TMPDIR: tmpInSandbox,
    TEMP: tmpInSandbox,
    TMP: tmpInSandbox,
    LANG: process.env.LANG || 'C.UTF-8',
    LC_ALL: process.env.LC_ALL || process.env.LANG || 'C.UTF-8',
    TERM: process.env.TERM || 'xterm',
    PYTHONUNBUFFERED: '1',
    // 减轻 VM/Hyper-V 上 IPv6 黑洞导致的 HTTPS 长时间挂起（sitecustomize + gai.conf）
    PYTHONENV_PREFER_IPV4: '1',
    ...(existsSync(caBundle)
      ? { SSL_CERT_FILE: caBundle, REQUESTS_CA_BUNDLE: caBundle, CURL_CA_BUNDLE: caBundle }
      : {}),
    ...opts.env,
  };

  // 在 /etc 只读绑定之后覆盖 gai.conf，使 glibc getaddrinfo（含 C 扩展）优先 IPv4
  const preferV4 = ['1', 'true', 'yes'].includes(
    String(env.PYTHONENV_PREFER_IPV4 ?? '1').trim().toLowerCase(),
  );
  if (preferV4) {
    const gaiPath = join(work, VENV_STATE_DIR, 'gai-prefer-ipv4.conf');
    mkdirSync(join(work, VENV_STATE_DIR), { recursive: true });
    writeFileSync(gaiPath, GAI_CONF_PREFER_IPV4, 'utf8');
    args.push('--ro-bind', gaiPath, '/etc/gai.conf');
  }

  args.push('--chdir', cwd);
  args.push('--clearenv');
  for (const [key, value] of Object.entries(env)) {
    if (value === undefined || value === null) continue;
    args.push('--setenv', key, String(value));
  }

  args.push('--', '/bin/sh', '-c', opts.command);
  return args;
}

/**
 * Linux bubblewrap runner：与 MXC 目标对齐的进程隔离。
 * 缺 `bwrap` 时硬失败并提示 `apt install bubblewrap`。
 */
export class BwrapCommandRunner implements CommandRunner {
  async run(req: RunRequest): Promise<RunResult> {
    const dbg = (level: 'info' | 'warn' | 'error', msg: string, data?: unknown) =>
      writeDebug(req.workDirAbs, level, `bwrap: ${msg}`, data);

    if (process.platform !== 'linux') {
      throw new Error('cortico-world-pythonenv bubblewrap runner supports Linux only.');
    }
    if (req.containment === 'windows_sandbox' || req.containment === 'process') {
      dbg('warn', 'containment coerced to bwrap on Linux', { requested: req.containment });
    }

    let bwrapBin: string;
    try {
      bwrapBin = resolveBwrapBinary();
    } catch (e) {
      dbg('error', 'bwrap missing', { err: e instanceof Error ? e.message : String(e) });
      throw e;
    }

    const argv = buildBwrapArgv({
      workDirAbs: req.workDirAbs,
      cwd: req.cwd,
      command: req.command,
      env: req.env,
      readonlyPaths: req.readonlyPaths,
    });

    dbg('info', 'run', {
      bwrapBin,
      command: req.command,
      cwd: req.cwd,
      timeoutMs: req.timeoutMs,
      argvHead: argv.slice(0, 24),
      argvLen: argv.length,
    });

    try {
      const result = await spawnBwrap(bwrapBin, argv, req.timeoutMs);
      writeDebugOutputFiles(req.workDirAbs, 'bwrap', {
        stdout: result.stdout,
        stderr: result.stderr,
      });
      dbg('info', 'run finished', {
        exitCode: result.exitCode,
        timedOut: result.timedOut,
        stdoutLen: result.stdout.length,
        stderrLen: result.stderr.length,
        stderrHead: result.stderr.slice(0, 500),
      });
      return result;
    } catch (e) {
      dbg('error', 'run threw', {
        err: e instanceof Error ? e.message : String(e),
        stack: e instanceof Error ? e.stack : undefined,
      });
      throw e;
    }
  }
}

function spawnBwrap(bin: string, argv: string[], timeoutMs: number): Promise<RunResult> {
  return new Promise((resolve) => {
    const child = spawn(bin, argv, {
      stdio: ['ignore', 'pipe', 'pipe'],
      detached: true,
    });
    let stdout = '';
    let stderr = '';
    let timedOut = false;
    let settled = false;

    const finish = (exitCode: number) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve({ stdout, stderr, exitCode, timedOut });
    };

    const timer = setTimeout(() => {
      timedOut = true;
      killTree(child.pid);
    }, timeoutMs);

    child.stdout?.on('data', (c) => {
      stdout += String(c);
    });
    child.stderr?.on('data', (c) => {
      stderr += String(c);
    });
    child.on('error', (err) => {
      const msg = err.message || String(err);
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') {
        stderr = `${stderr}\n${BWRAP_INSTALL_HINT}`.trim();
      } else {
        stderr = `${stderr}\n${msg}`.trim();
      }
      finish(1);
    });
    child.on('close', (code, signal) => {
      if (timedOut) {
        finish(code ?? 1);
        return;
      }
      if (signal) {
        stderr = `${stderr}\nkilled by signal ${signal}`.trim();
        finish(code ?? 1);
        return;
      }
      finish(code ?? 1);
    });
  });
}

function killTree(pid: number | undefined): void {
  if (pid === undefined) return;
  try {
    process.kill(-pid, 'SIGKILL');
  } catch {
    try {
      process.kill(pid, 'SIGKILL');
    } catch {
      /* already dead */
    }
  }
}

function uniquePaths(paths: string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const p of paths) {
    const key = p.replace(/[\\/]+$/, '');
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(key);
  }
  return out;
}

function isInsideWorkDir(path: string, workDir: string): boolean {
  const norm = (s: string) => s.replace(/\\/g, '/').replace(/\/+$/, '');
  const w = norm(workDir);
  const p = norm(path);
  return p === w || p.startsWith(`${w}/`);
}
